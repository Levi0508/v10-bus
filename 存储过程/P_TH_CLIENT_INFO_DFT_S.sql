-- 保存/提交：只写上面三张草稿表。正式客户表不写。过程内不 COMMIT，由调用方事务提交
CREATE OR REPLACE PROCEDURE THJS.P_TH_CLIENT_INFO_DFT_S (
    I_CLIENT_ID IN VARCHAR2,
    I_CLIENT_NAME IN VARCHAR2,
    I_ORGAN_FLAG IN VARCHAR2,
    I_ID_TYPE IN VARCHAR2,
    I_ID_NO IN VARCHAR2,
    I_ID_BEGINDATE IN VARCHAR2,
    I_ID_ENDDATE IN VARCHAR2,
    I_CLIENT_BELONG IN VARCHAR2,
    I_NATIONALITY IN VARCHAR2,
    I_BIRTHDAY IN VARCHAR2,
    I_OFFICE_ADDRESS IN VARCHAR2,
    I_PROVINCE IN VARCHAR2,
    I_CITY IN VARCHAR2,
    I_DISTRICT IN VARCHAR2,
    I_REGISTER_COUNTRY IN VARCHAR2,
    I_REGISTER_MONEY_TYPE IN VARCHAR2,
    I_REGISTER_FUND IN VARCHAR2,
    I_INDUSTRY_TYPE IN VARCHAR2,
    I_TEL IN VARCHAR2,
    I_SETUP_DATE IN VARCHAR2,
    I_BUSI_SCOPE IN VARCHAR2,
    I_IS_OBJECT_REPORT IN VARCHAR2,
    I_ASSOCIATED_DATE IN VARCHAR2,
    I_REMARK IN VARCHAR2,
    I_CREATE_USER IN VARCHAR2,
    I_CREATE_TIME IN VARCHAR2,
    I_UPDATE_USER IN VARCHAR2,
    I_UPDATE_TIME IN VARCHAR2,
    I_IS_SPECIAL IN VARCHAR2,
    I_CLIENT_TYPE IN VARCHAR2,
    I_CLIENT_TYPE_OTHER IN VARCHAR2,
    I_SPECIAL_MATTERS IN VARCHAR2,
    I_MISSING_INFORMATION IN VARCHAR2,
    I_MISSING_DRAFT IN VARCHAR2,
    I_SPECIAL_MATTERS_OTHER IN VARCHAR2,
    I_SPECIAL_REASON IN VARCHAR2,
    I_COMPLETED_CDD IN VARCHAR2,
    I_LOW_RISK_EXPLANATION IN VARCHAR2,
    I_TAKE_MEASURES IN VARCHAR2,
    I_COMMUNICATION_RECORDS IN VARCHAR2,
    I_AGREE_RECORDS IN VARCHAR2,
    I_OTHER_RECORDS IN VARCHAR2,
    I_INDUSTRY_TYPE1 IN VARCHAR2,
    I_WORK_TYPE IN VARCHAR2,
    I_CLIENT_STATUS IN VARCHAR2,
    I_DATA_STATUS IN VARCHAR2,
    I_RELATED_PROJ IN VARCHAR2,
    I_IF_RISK_CLIENT IN VARCHAR2,
    I_RISK_LIST_TYPE IN VARCHAR2,
    I_PROBLEM_DESC IN VARCHAR2,
    I_GRADE_VALUE IN VARCHAR2,
    I_GENDER IN VARCHAR2,
    I_INCOME IN VARCHAR2,
    I_PROFESSION_CODE IN VARCHAR2,
    I_POSITION IN VARCHAR2,
    I_WORK_PLACE IN VARCHAR2,
    I_ZIPCODE IN VARCHAR2,
    I_FILLIN_DATE IN VARCHAR2,
    I_ID_ADDRESS IN VARCHAR2,
    I_PROVINCE1 IN VARCHAR2,
    I_CITY1 IN VARCHAR2,
    I_DISTRICT1 IN VARCHAR2,
    I_ADDRESS IN VARCHAR2,
    I_PROVINCE2 IN VARCHAR2,
    I_CITY2 IN VARCHAR2,
    I_DISTRICT2 IN VARCHAR2,
    I_IF_RISK_LIST IN VARCHAR2,
    I_INDUSTRY_NAME IN VARCHAR2,
    I_SAVE_TYPE IN VARCHAR2,
    I_BASE_VER_ID IN VARCHAR2,
    I_BATCH_JSON IN CLOB,
    O_RETURN_MSG OUT VARCHAR2,
    O_RETURN_CODE OUT INTEGER
) AS
    v_latest_ver   VARCHAR2(32);
    v_latest_no    INT;
    v_latest_stat  CHAR(1);
    v_ver_id       VARCHAR2(32);
    v_ver_no       INT;
    v_status       CHAR(1);
    v_save_type    VARCHAR2(10);
    v_cnt          INT;
    v_formal       INT;
BEGIN
    -- 默认成功。SAVE_TYPE 空当成 save；submit 状态 1，否则 0
    O_RETURN_CODE := 0;
    O_RETURN_MSG := '成功';
    v_save_type := NVL(NULLIF(TRIM(I_SAVE_TYPE), ''), 'save');
    v_status := CASE WHEN v_save_type = 'submit' THEN '1' ELSE '0' END;

    -- 取这个客户最新一版的版本号、序号、状态
    SELECT MAX(VER_ID), MAX(VER_NO), MAX(DFT_STATUS)
      INTO v_latest_ver, v_latest_no, v_latest_stat
      FROM (
            SELECT VER_ID, VER_NO, DFT_STATUS
              FROM THJS.T_TH_CLIENT_DFT_VER
             WHERE CLIENT_ID = I_CLIENT_ID
             ORDER BY VER_NO DESC
           )
     WHERE ROWNUM = 1;

    -- 待审中不允许再改
    IF v_latest_stat = '1' THEN
        O_RETURN_CODE := -1;
        O_RETURN_MSG := '待审核期间不可修改';
        RETURN;
    END IF;

    -- 最新是草稿或退回时，必须基于这一版。对不上说明别人已经保存过
    IF v_latest_ver IS NOT NULL AND v_latest_stat IN ('0', '2')
       AND NVL(TRIM(I_BASE_VER_ID), '#') <> v_latest_ver THEN
        O_RETURN_CODE := -1;
        O_RETURN_MSG := '数据已被更新，请刷新';
        RETURN;
    END IF;

    -- 机构客户、归属为 1：正式表已有同名则拒绝
    SELECT COUNT(1) INTO v_cnt
      FROM THJS.T_TH_CLIENT_INFO a
     WHERE a.CLIENT_ID <> I_CLIENT_ID
       AND a.CLIENT_BELONG = '1'
       AND a.CLIENT_NAME = I_CLIENT_NAME
       AND I_ORGAN_FLAG = '1'
       AND I_CLIENT_BELONG = '1';
    IF v_cnt > 0 THEN
        O_RETURN_CODE := -1;
        O_RETURN_MSG := '已存在相同名称的机构客户';
        RETURN;
    END IF;

    -- 其他客户最新草稿（状态 0/1/2）里已有同名机构则拒绝
    SELECT COUNT(1) INTO v_cnt
      FROM THJS.T_TH_CLIENT_INFO_DFT d
      JOIN THJS.T_TH_CLIENT_DFT_VER v ON v.VER_ID = d.VER_ID
     WHERE v.CLIENT_ID <> I_CLIENT_ID
       AND v.DFT_STATUS IN ('0', '1', '2')
       AND v.VER_NO = (SELECT MAX(v2.VER_NO) FROM THJS.T_TH_CLIENT_DFT_VER v2 WHERE v2.CLIENT_ID = v.CLIENT_ID)
       AND d.CLIENT_BELONG = '1'
       AND d.CLIENT_NAME = I_CLIENT_NAME
       AND I_ORGAN_FLAG = '1'
       AND I_CLIENT_BELONG = '1';
    IF v_cnt > 0 THEN
        O_RETURN_CODE := -1;
        O_RETURN_MSG := '已存在相同名称的机构客户草稿';
        RETURN;
    END IF;

    -- 证件号非空：正式表和其他客户最新草稿都不能重复
    IF TRIM(I_ID_NO) IS NOT NULL THEN
        SELECT COUNT(1) INTO v_cnt
          FROM THJS.T_TH_CLIENT_INFO a
         WHERE a.CLIENT_ID <> I_CLIENT_ID
           AND a.ID_NO = I_ID_NO;
        IF v_cnt > 0 THEN
            O_RETURN_CODE := -1;
            O_RETURN_MSG := '已存在相同证件号的客户';
            RETURN;
        END IF;
        SELECT COUNT(1) INTO v_cnt
          FROM THJS.T_TH_CLIENT_INFO_DFT d
          JOIN THJS.T_TH_CLIENT_DFT_VER v ON v.VER_ID = d.VER_ID
         WHERE v.CLIENT_ID <> I_CLIENT_ID
           AND v.DFT_STATUS IN ('0', '1', '2')
           AND v.VER_NO = (SELECT MAX(v2.VER_NO) FROM THJS.T_TH_CLIENT_DFT_VER v2 WHERE v2.CLIENT_ID = v.CLIENT_ID)
           AND d.ID_NO = I_ID_NO;
        IF v_cnt > 0 THEN
            O_RETURN_CODE := -1;
            O_RETURN_MSG := '已存在相同证件号的客户草稿';
            RETURN;
        END IF;
    END IF;

    -- 新版本号。没有历史版本则从 1 开始
    v_ver_id := SYS_GUID();
    v_ver_no := NVL(v_latest_no, 0) + 1;

    -- 版本头。提交时同时写提交人和提交时间
    INSERT INTO THJS.T_TH_CLIENT_DFT_VER (
        VER_ID, CLIENT_ID, VER_NO, BASE_VER_ID, DFT_STATUS, SAVE_TYPE,
        CREATE_USER, CREATE_TIME, SUBMIT_USER, SUBMIT_TIME
    ) VALUES (
        v_ver_id, I_CLIENT_ID, v_ver_no, NULLIF(TRIM(I_BASE_VER_ID), ''), v_status, v_save_type,
        I_UPDATE_USER, SYSDATE,
        CASE WHEN v_save_type = 'submit' THEN I_UPDATE_USER END,
        CASE WHEN v_save_type = 'submit' THEN SYSDATE END
    );

    -- 本版客户基本信息。注册资金空串转成空数字；创建、更新时间用 SYSDATE
    INSERT INTO THJS.T_TH_CLIENT_INFO_DFT (
        CLIENT_ID, CLIENT_NAME, ORGAN_FLAG, ID_TYPE, ID_NO, ID_BEGINDATE, ID_ENDDATE, CLIENT_BELONG,
        NATIONALITY, BIRTHDAY, OFFICE_ADDRESS, PROVINCE, CITY, DISTRICT, REGISTER_COUNTRY, REGISTER_MONEY_TYPE,
        REGISTER_FUND, INDUSTRY_TYPE, TEL, SETUP_DATE, BUSI_SCOPE, IS_OBJECT_REPORT, ASSOCIATED_DATE, REMARK,
        CREATE_USER, CREATE_TIME, UPDATE_USER, UPDATE_TIME, IS_SPECIAL, CLIENT_TYPE, CLIENT_TYPE_OTHER,
        SPECIAL_MATTERS, MISSING_INFORMATION, MISSING_DRAFT, SPECIAL_MATTERS_OTHER, SPECIAL_REASON,
        COMPLETED_CDD, LOW_RISK_EXPLANATION, TAKE_MEASURES, COMMUNICATION_RECORDS, AGREE_RECORDS, OTHER_RECORDS,
        INDUSTRY_TYPE1, WORK_TYPE, CLIENT_STATUS, DATA_STATUS, RELATED_PROJ, IF_RISK_CLIENT, RISK_LIST_TYPE,
        PROBLEM_DESC, GRADE_VALUE, GENDER, INCOME, PROFESSION_CODE, POSITION, WORK_PLACE, ZIPCODE, FILLIN_DATE,
        ID_ADDRESS, PROVINCE1, CITY1, DISTRICT1, ADDRESS, PROVINCE2, CITY2, DISTRICT2, IF_RISK_LIST, INDUSTRY_NAME,
        VER_ID
    ) VALUES (
        I_CLIENT_ID, I_CLIENT_NAME, I_ORGAN_FLAG, I_ID_TYPE, I_ID_NO, I_ID_BEGINDATE, I_ID_ENDDATE, I_CLIENT_BELONG,
        I_NATIONALITY, I_BIRTHDAY, I_OFFICE_ADDRESS, I_PROVINCE, I_CITY, I_DISTRICT, I_REGISTER_COUNTRY, I_REGISTER_MONEY_TYPE,
        TO_NUMBER(NULLIF(TRIM(I_REGISTER_FUND), '')), I_INDUSTRY_TYPE, I_TEL, I_SETUP_DATE, I_BUSI_SCOPE, I_IS_OBJECT_REPORT,
        I_ASSOCIATED_DATE, I_REMARK, I_CREATE_USER, SYSDATE, I_UPDATE_USER, SYSDATE, I_IS_SPECIAL, I_CLIENT_TYPE,
        I_CLIENT_TYPE_OTHER, I_SPECIAL_MATTERS, I_MISSING_INFORMATION, I_MISSING_DRAFT, I_SPECIAL_MATTERS_OTHER,
        I_SPECIAL_REASON, I_COMPLETED_CDD, I_LOW_RISK_EXPLANATION, I_TAKE_MEASURES, I_COMMUNICATION_RECORDS,
        I_AGREE_RECORDS, I_OTHER_RECORDS, I_INDUSTRY_TYPE1, NVL(I_WORK_TYPE, '1'), NVL(I_CLIENT_STATUS, '0'),
        NVL(I_DATA_STATUS, '0'), I_RELATED_PROJ, I_IF_RISK_CLIENT, I_RISK_LIST_TYPE, I_PROBLEM_DESC, I_GRADE_VALUE,
        I_GENDER, I_INCOME, I_PROFESSION_CODE, I_POSITION, I_WORK_PLACE, I_ZIPCODE, I_FILLIN_DATE, I_ID_ADDRESS,
        I_PROVINCE1, I_CITY1, I_DISTRICT1, I_ADDRESS, I_PROVINCE2, I_CITY2, I_DISTRICT2, I_IF_RISK_LIST, I_INDUSTRY_NAME,
        v_ver_id
    );

    -- batchList 不是空数组时，拆成关联人多行写入本版。无编号或 tmp_ 开头则新生成编号
    -- 方括号用 CHR(91)、CHR(93) 拼，避免达梦执行窗口把方括号当成语法
    IF I_BATCH_JSON IS NOT NULL AND TRIM(I_BATCH_JSON) IS NOT NULL
       AND TRIM(I_BATCH_JSON) <> CHR(91) || CHR(93) THEN
        INSERT INTO THJS.T_TH_RELAT_INFO_DFT (
            CLIENT_ID, RELATED_ID, RELATED_TYPE, ORGAN_FLAG, RELATED_NAME, NATIONALITY, ID_TYPE, ID_NO,
            ID_BEGINDATE, ID_ENDDATE, BIRTHDAY, SHAREHOLDING_RATIO, BENEFICIARY, ADDRESS, IS_GOVERNMENT_DEPT,
            OBJECT_ID, CREATE_USER, CREATE_TIME, UPDATE_USER, UPDATE_TIME, DATA_STATUS, GENDER, MOBNO1, MOBNO2,
            ACTHDRAT, ACTCTRLTYPE, ACTOTHERFORMS, ACTCONUPPERMARKET, ACTCONUPPERENTNAME, ACTCONUNISCID,
            ACTOWNERPROFITRATIO, ACTOWNERPROFITRATIOVOTE, SENIORMGRPOS, ACTDAILYMGMTPOSTOTHER, SENIORMGRPOSCN,
            OWNERRIGHTMGMTPOSTOTHER, BNF_TYPE, BO_TYPE, COMPANY_TYPE, FULL_INFO_FLAG, VER_ID
        )
        SELECT I_CLIENT_ID,
               CASE
                   WHEN j.related_id IS NULL OR TRIM(j.related_id) = '' OR j.related_id LIKE 'tmp_%' THEN SYS_GUID()
                   ELSE SUBSTR(j.related_id, 1, 32)
               END,
               SUBSTR(j.related_type, 1, 1),
               SUBSTR(j.organ_flag, 1, 1),
               j.related_name, j.nationality, j.id_type, j.id_no, j.id_begindate, j.id_enddate, j.birthday,
               j.shareholding_ratio, j.beneficiary, j.address, SUBSTR(j.is_government_dept, 1, 1), j.object_id,
               NVL(I_UPDATE_USER, 'admin'), SYSDATE, I_UPDATE_USER, SYSDATE, '0', j.gender, j.mobno1, j.mobno2,
               TO_NUMBER(NULLIF(TRIM(j.acthdrat), '')),
               SUBSTR(REPLACE(REPLACE(REPLACE(NVL(j.actctrltype, ''), CHR(91), ''), CHR(93), ''), '"', ''), 1, 10),
               j.actotherforms, j.actconuppermarket, j.actconupperentname, j.actconuniscid,
               TO_NUMBER(NULLIF(TRIM(j.actownerprofitratio), '')),
               TO_NUMBER(NULLIF(TRIM(j.actownerprofitratiovote), '')),
               SUBSTR(REPLACE(REPLACE(REPLACE(NVL(j.seniormgrpos, ''), CHR(91), ''), CHR(93), ''), '"', ''), 1, 10),
               j.actdailymgmtpostother,
               SUBSTR(REPLACE(REPLACE(REPLACE(NVL(j.seniormgrposcn, ''), CHR(91), ''), CHR(93), ''), '"', ''), 1, 10),
               j.ownerrightmgmtpostother,
               SUBSTR(REPLACE(REPLACE(REPLACE(NVL(j.bnf_type, ''), CHR(91), ''), CHR(93), ''), '"', ''), 1, 20),
               j.bo_type, j.company_type, j.full_info_flag, v_ver_id
          FROM JSON_TABLE(I_BATCH_JSON, '$' || CHR(91) || '*' || CHR(93) COLUMNS (
                   related_id VARCHAR2(64) PATH '$.RELATED_ID',
                   related_type VARCHAR2(10) PATH '$.RELATED_TYPE',
                   organ_flag VARCHAR2(10) PATH '$.ORGAN_FLAG',
                   related_name VARCHAR2(200) PATH '$.RELATED_NAME',
                   nationality VARCHAR2(50) PATH '$.NATIONALITY',
                   id_type VARCHAR2(10) PATH '$.ID_TYPE',
                   id_no VARCHAR2(50) PATH '$.ID_NO',
                   id_begindate VARCHAR2(20) PATH '$.ID_BEGINDATE',
                   id_enddate VARCHAR2(20) PATH '$.ID_ENDDATE',
                   birthday VARCHAR2(20) PATH '$.BIRTHDAY',
                   shareholding_ratio VARCHAR2(20) PATH '$.SHAREHOLDING_RATIO',
                   beneficiary VARCHAR2(20) PATH '$.BENEFICIARY',
                   address VARCHAR2(300) PATH '$.ADDRESS',
                   is_government_dept VARCHAR2(10) PATH '$.IS_GOVERNMENT_DEPT',
                   object_id VARCHAR2(4000) PATH '$.OBJECT_ID',
                   gender VARCHAR2(4) PATH '$.GENDER',
                   mobno1 VARCHAR2(16) PATH '$.MOBNO1',
                   mobno2 VARCHAR2(16) PATH '$.MOBNO2',
