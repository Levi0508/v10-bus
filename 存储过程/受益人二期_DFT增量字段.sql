-- 已有 DFT 表的环境执行。随后部署 P_TH_CLIENT_INFO_DFT_S，再更新 fxq 模块。
ALTER TABLE THJS.T_TH_CLIENT_DFT_VER
ADD (
    BENEFIT_COMPANY_TYPE VARCHAR2 (200),
    BENEFIT_BO_TYPE VARCHAR2 (200),
    BENEFIT_FULL_INFO_FLAG VARCHAR2 (200)
);

ALTER TABLE THJS.T_TH_RELAT_INFO_DFT
ADD (
    BENEFIT_START_DATE TIMESTAMP(0),
    BENEFIT_END_DATE TIMESTAMP(0),
    SENIORMGRCN_START_DATE TIMESTAMP(0),
    SENIORMGRCN_END_DATE TIMESTAMP(0)
);

-- 已扩长过的环境保留现有长度。
BEGIN
    FOR col IN (
        SELECT COLUMN_NAME,
               CASE COLUMN_NAME WHEN 'BNF_TYPE' THEN 64 ELSE 32 END AS target_length
        FROM ALL_TAB_COLUMNS
        WHERE OWNER = 'THJS'
          AND TABLE_NAME = 'T_TH_RELAT_INFO_DFT'
          AND ((COLUMN_NAME = 'BNF_TYPE' AND CHAR_LENGTH < 64)
               OR (COLUMN_NAME = 'SENIORMGRPOS' AND CHAR_LENGTH < 32))
    ) LOOP
        EXECUTE IMMEDIATE 'ALTER TABLE THJS.T_TH_RELAT_INFO_DFT MODIFY ('
            || col.COLUMN_NAME || ' VARCHAR2(' || col.target_length || '))';
    END LOOP;
END;
